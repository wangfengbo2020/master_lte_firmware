	//[REGN] DDR_HEAP
	//[DESC] Os HEAP region
	//[SIZE] 1.2M
    #define DDR_HEAP_BASE_ADDR (MSA_BASE_ADDR + MSA_SIZE)
    #define DDR_HEAP_SIZE      (0x00140000)     //1280K

    //[REGN] DDR_RW_DATA
	//[DESC] RW data
	//[SIZE] 1.2M
    #define DDR_RW_DATA_BASE_ADDR  (DDR_HEAP_BASE_ADDR + DDR_HEAP_SIZE)
    #define DDR_RW_DATA_SIZE       (0x000B4000)


	//[REGN] PS_CODE_IN_PSRAM
	//[DESC] effective essential code running on PSRAM
	//[SIZE] 320K
	#define PS_CODE_IN_PSRAM_BASE  (DDR_RW_DATA_BASE_ADDR + DDR_RW_DATA_SIZE)
	#define PS_CODE_IN_PSRAM_SIZE   (0x00037000)
    #define PSB_CODE_IN_PSRAM_SIZE  (0x00041000)
    #define PSC_CODE_IN_PSRAM_SIZE  (0x00041000)
    #define PSD_CODE_IN_PSRAM_SIZE  (0x0002A000)
    //0x00037000
    #define PSE_CODE_IN_PSRAM_SIZE  (0x0012E000 - PS_CODE_IN_PSRAM_SIZE - PSB_CODE_IN_PSRAM_SIZE - PSC_CODE_IN_PSRAM_SIZE - PSD_CODE_IN_PSRAM_SIZE)




