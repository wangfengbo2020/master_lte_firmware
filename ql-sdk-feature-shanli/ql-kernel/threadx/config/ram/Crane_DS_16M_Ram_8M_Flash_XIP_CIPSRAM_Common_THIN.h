#define QSPI_BASE_ADDR  (0x80038000)
#define DDR_RO_SIZE     (0x00A00000)
#define PSRAM_BASE_ADDR (0x7E000000)
#define PSRAM_SIZE      (0x01000000)
#define PSRAM_END_MARK  (PSRAM_BASE_ADDR + PSRAM_SIZE)

//PSRAM_BLOCK_1
	//[REGN] DDR_DSP_RO
	//[DESC] DSP image load region
	//[SIZE] 1.5M
	#define MSA_BASE_ADDR   (PSRAM_BASE_ADDR)
	#ifdef DM_LTEONLY_16MPSRAM
	#define MSA_SIZE        (0x00140000)
	#else
	#define MSA_SIZE        (0x00210000)
	#endif

	//[REGN] PS_CODE_IN_PSRAM & DDR_RW_DATA
	//[DESC] effective essential code running on PSRAM & RW data
	//[SIZE] 4M
	#define PS_CODE_IN_PSRAM_BASE  (MSA_BASE_ADDR + MSA_SIZE)
#ifdef DM_LTEONLY_16MPSRAM
	#define PS_CODE_IN_PSRAM_SIZE  (0x004D0000 - NON_OTA_CODE_IN_PSRAM_SIZE - PSB_CODE_IN_PSRAM_SIZE - PL_CODE_IN_PSRAM_SIZE)//0x00120000
	#define PSB_CODE_IN_PSRAM_SIZE (0x000D0000)
	#define PL_CODE_IN_PSRAM_SIZE  (0x001E0000)
	#define APP_CODE_IN_PSRAM_SIZE (0x00010000)
	#define NON_OTA_CODE_IN_PSRAM_SIZE  (0x00100000)
	#define DDR_RW_DATA_BASE_ADDR  (PS_CODE_IN_PSRAM_BASE + PS_CODE_IN_PSRAM_SIZE + PSB_CODE_IN_PSRAM_SIZE + PL_CODE_IN_PSRAM_SIZE + NON_OTA_CODE_IN_PSRAM_SIZE + APP_CODE_IN_PSRAM_SIZE)
	#define DDR_RW_DATA_SIZE       (0x00200000)
#else
	#ifdef QUECTEL_OPEN_CPU
		#define PS_CODE_IN_PSRAM_SIZE  		(0x0023A000)
		#define PSB_CODE_IN_PSRAM_SIZE 		(0x00235000)
		#define PL_CODE_IN_PSRAM_SIZE  		(0x0015C000)
		#define NON_OTA_CODE_IN_PSRAM_SIZE  (0x000F0000)
		#define APP_CODE_IN_PSRAM_SIZE 		(0x00180000)
		#define DDR_RW_DATA_BASE_ADDR  		(PS_CODE_IN_PSRAM_BASE + PS_CODE_IN_PSRAM_SIZE + PSB_CODE_IN_PSRAM_SIZE + PL_CODE_IN_PSRAM_SIZE + NON_OTA_CODE_IN_PSRAM_SIZE + APP_CODE_IN_PSRAM_SIZE)
		#define DDR_RW_DATA_SIZE       		(0x00200000)
	#else
		#define PS_CODE_IN_PSRAM_SIZE  		(0x0023A000)
		#define PSB_CODE_IN_PSRAM_SIZE 		(0x00235000)
		#define PL_CODE_IN_PSRAM_SIZE  		(0x00160000)
		#define NON_OTA_CODE_IN_PSRAM_SIZE  (0x00260000)
		#define APP_CODE_IN_PSRAM_SIZE 		(0x00000100)
		#define DDR_RW_DATA_BASE_ADDR  		(PS_CODE_IN_PSRAM_BASE + PS_CODE_IN_PSRAM_SIZE + PSB_CODE_IN_PSRAM_SIZE + PL_CODE_IN_PSRAM_SIZE + NON_OTA_CODE_IN_PSRAM_SIZE + APP_CODE_IN_PSRAM_SIZE)
		#define DDR_RW_DATA_SIZE       		(0x00200000)
	#endif
		#define PSB_CODE_IN_PSRAM_BASE  	(PS_CODE_IN_PSRAM_BASE + PS_CODE_IN_PSRAM_SIZE)
		#define PL_CODE_IN_PSRAM_BASE   	(PSB_CODE_IN_PSRAM_BASE + PSB_CODE_IN_PSRAM_SIZE)
		#define NON_OTA_CODE_IN_PSRAM_BASE  (PL_CODE_IN_PSRAM_BASE + PL_CODE_IN_PSRAM_SIZE)
		#define APP_CODE_IN_PSRAM_BASE 		(NON_OTA_CODE_IN_PSRAM_BASE + NON_OTA_CODE_IN_PSRAM_SIZE)
		
#endif

//PSRAM_BLOCK_2
	//[REGN] NONCACHE_REGION
	//[DESC] ALL NONCACHE regions
	//[SIZE] 1M
	#define DDR_NONCACHE_AREA_TOTAL_SIZE     (0x00100000)
	#define DDR_NONCACHE_AREA_TOTAL_START    (PSRAM_BASE_ADDR + PSRAM_SIZE - DDR_NONCACHE_AREA_TOTAL_SIZE)
	#define DDR_NONCACHE_PS_UL_BASE_ADDR     (DDR_NONCACHE_AREA_TOTAL_START)
	#define DDR_NONCACHE_PS_UL_SIZE          (0x00019000)
	#define DDR_NONCACHE_PS_DL_BASE_ADDR     (DDR_NONCACHE_PS_UL_BASE_ADDR + DDR_NONCACHE_PS_UL_SIZE)
	#define DDR_NONCACHE_PS_DL_SIZE          (0x00019000)
	#define PS_NONCACHE_DATA_BASE_ADDR       (DDR_NONCACHE_PS_DL_BASE_ADDR + DDR_NONCACHE_PS_DL_SIZE)
	#define PS_NONCACHE_DATA_SIZE            (0x00070000)
	#define DDR_NONCACHE_BASE_ADDR           (PS_NONCACHE_DATA_BASE_ADDR + PS_NONCACHE_DATA_SIZE)
	#define DDR_NONCACHE_SIZE                (0x00001000)
	#define D2_VECT_BASE_ADDR                (DDR_NONCACHE_BASE_ADDR + DDR_NONCACHE_SIZE)
	#define D2_VECT_SIZE                     (0x00001000)
	#define DDR_PRIVATE_RW_AREA_BASE_ADDR    (D2_VECT_BASE_ADDR + D2_VECT_SIZE)
	#define DDR_PRIVATE_RW_AREA_SIZE         (0x00001C00 - 0x0)
	#define DDR_NONCACHE_PTABLE_BASE_ADDR    (DDR_PRIVATE_RW_AREA_BASE_ADDR + DDR_PRIVATE_RW_AREA_SIZE)
	#define DDR_NONCACHE_PTABLE_SIZE         (0x00001000)
	#define DDR_NONCACHE_PROP_BASE_ADDR      (DDR_NONCACHE_PTABLE_BASE_ADDR + DDR_NONCACHE_PTABLE_SIZE)
	#define DDR_NONCACHE_PROP_SIZE           (0x00001000)
	#define DDR_NONCACHE_USB_BASE_ADDR       (DDR_NONCACHE_PROP_BASE_ADDR + DDR_NONCACHE_PROP_SIZE)
	#define DDR_NONCACHE_USB_SIZE            (DDR_NONCACHE_AREA_TOTAL_SIZE - (DDR_NONCACHE_USB_BASE_ADDR - DDR_NONCACHE_AREA_TOTAL_START))

